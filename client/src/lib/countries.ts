export type CountryCode = (typeof COUNTRY_CODES)[number];

const displayNames = new Map<string, Intl.DisplayNames>();

/** Tên quốc gia theo ngôn ngữ (vd. "US" → "Hoa Kỳ" / "United States"); mã lạ → trả lại nguyên giá trị */
export function countryName(code: string | null | undefined, locale: string): string {
  if (!code) return "";
  let dn = displayNames.get(locale);
  if (!dn) {
    dn = new Intl.DisplayNames([locale], { type: "region", fallback: "code" });
    displayNames.set(locale, dn);
  }
  try {
    return dn.of(code.toUpperCase()) ?? code;
  } catch {
    return code; // giá trị cũ không phải mã ISO (vd. chữ tự do) → hiện nguyên văn
  }
}
